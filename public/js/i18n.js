class I18nService {
  static currentLang = 'en';

  static init(lang = 'en') {
    this.currentLang = ['en', 'hi', 'pa', 'mr'].includes(lang) ? lang : 'en';
  }

  static setLang(lang) {
    if (['en', 'hi', 'pa', 'mr'].includes(lang)) {
      this.currentLang = lang;
      localStorage.setItem('agrichain_lang', lang);
    }
  }

  static t(path) {
    const keys = path.split('.');
    let current = I18N[this.currentLang] || I18N['en'];
    for (const key of keys) {
      if (current && current[key] !== undefined) {
        current = current[key];
      } else {
        // Fallback to English
        let fallback = I18N['en'];
        for (const fbKey of keys) {
          if (fallback && fallback[fbKey] !== undefined) {
            fallback = fallback[fbKey];
          } else {
            return path;
          }
        }
        return fallback;
      }
    }
    return current;
  }
}

window.I18nService = I18nService;
